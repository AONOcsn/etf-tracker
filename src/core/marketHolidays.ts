export const HOLIDAY_TABLE_NOTE =
  `节假日表已核对到 ${LAST_VERIFIED_YEAR} 年。超出范围的日期只判断周末，` +
  '无法确认是否休市，请以交易所公告为准。'

/** 节假日表查询所需的最小接口，便于测试注入假表。 */
export interface HolidayLookup {
  holiday(nyDate: string): string | undefined
  earlyClose(nyDate: string): string | undefined
  /** 该年份是否在已核对范围内。 */
  covered(year: number): boolean
}

/** 用内置表实现的查询器。 */
export const NYSE_CALENDAR: HolidayLookup = {
  holiday: nyDate => NYSE_HOLIDAYS[nyDate],
  earlyClose: nyDate => NYSE_EARLY_CLOSES[nyDate],
  covered: year => year <= LAST_VERIFIED_YEAR
}
